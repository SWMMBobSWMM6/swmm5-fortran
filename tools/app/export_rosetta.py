"""export_rosetta.py - write the full-engine data the Code-Rosetta-Stone app shows in its "Full Engines" tab.

  python3 tools/app/export_rosetta.py OUT.json

Reads tools/app/data/summary.json (written by build_app.py from the stored gate runs and the benchmark), so
every number in the tab is the measured one. Written by Claude (Anthropic); see AI-USE.md.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'data', 'summary.json')))
T, B, L = S['totals'], S.get('bench') or {}, S['lines']

ORG = 'https://github.com/SWMMBobSWMM6/'
META = [
    # key in totals, short name, language, repo, how it was made, lines, build, run
    ('EPA 5.2.4 (C)', 'EPA', 'C', 'https://github.com/USEPA/Stormwater-Management-Model/tree/v5.2.4',
     'The reference: EPA SWMM 5.2.4 from the v5.2.4 tag, gcc 13.3 -O2 on x86-64 Linux, glibc 2.39',
     L.get('c'), 'make (EPA CMake or the Makefile in swmm5-fortran/ref)', 'runswmm model.inp model.rpt model.out'),
    ('C++ swmm5-cplus', 'C++', 'C++17', ORG + 'swmm5-cplus',
     'EPA restructured as C++ classes', None,
     'tools/build_native.sh src/engine src/api build/native "-O2 -flto"', 'build/native/runswmm_cp model.inp model.rpt model.out'),
    ('Rust swmm5-rust', 'Rust', 'Rust (safe)', ORG + 'swmm5-rust',
     'c2rust baseline, then a translation into safe Rust (the engine crate forbids unsafe code)',
     (S.get('rust') or {}).get('lines'), 'cargo build --release', 'target/release/runswmm-rs model.inp model.rpt model.out'),
    ('Fortran', 'Fortran', 'Fortran 2008', ORG + 'swmm5-fortran',
     'generated from EPA\'s C by a libclang translator (tools/c2x) plus a hand-written runtime',
     L.get('f90_gen'), 'bash f90/build.sh', 'f90/bin/runswmm model.inp model.rpt model.out'),
    ('C#', 'C#', 'C# 12 / .NET 8', ORG + 'swmm5-csharp',
     'generated by the same translator plus a hand-written runtime', L.get('cs_gen'),
     'cd cs && ./build.sh', 'dotnet cs/bin/runswmm.dll model.inp model.rpt model.out'),
    ('Python', 'Python', 'Python 3 (pure)', ORG + 'swmm5-python',
     'generated by the same translator plus a hand-written runtime; standard library only', L.get('py_gen'),
     '(nothing to build)', 'python3 py/runswmm.py model.inp model.rpt model.out'),
    ('TypeScript', 'TypeScript', 'TypeScript (Node)', ORG + 'swmm5-typescript',
     'generated by the same translator plus a hand-written runtime with a bit-exact copy of glibc\'s math',
     L.get('ts_gen'), 'cd ts && npm install && npm run build', 'node ts/dist/runswmm.js model.inp model.rpt model.out'),
    ('Java', 'Java', 'Java 21', ORG + 'swmm5-java',
     'generated by the same translator plus a hand-written runtime with a bit-exact copy of glibc\'s math', L.get('java_gen'),
     'java/build.sh', 'java/runswmm model.inp model.rpt model.out'),
]
CPP_LINES = 53009   # src/engine/*.cpp and headers in swmm5-cplus at 1d7f52a (wc -l)

rows = []
for key, short, lang, repo, how, lines, build, run in META:
    t = T.get(key)
    if key.startswith('EPA'):
        gate = dict(status='reference')
    elif not t or not t.get('PASS'):
        continue                      # not gated (yet): not shown
    else:
        bad = sum(v for k, v in t.items() if k not in ('PASS', 'NOTRUN', 'rpt_lines', 'out_bytes'))
        gate = dict(status='identical' if not bad else 'differences', identical=t['PASS'], differ=bad,
                    notrun=t.get('NOTRUN', 0), out_bytes=t.get('out_bytes'), rpt_lines=t.get('rpt_lines'))
    if short == 'C++':
        lines = CPP_LINES
    cpu = None if short == 'EPA' else (B.get('median') or {}).get(short)
    rng = None if short == 'EPA' else (B.get('range') or {}).get(short)
    rows.append(dict(name=short, language=lang, repo=repo, how=how, lines=lines, build=build, run=run,
                     gate=gate, cpu=cpu, cpu_range=rng))

out = dict(n_models=S['n_models'], built=S['built'], essay=S.get('essay_title'),
           noise=B.get('noise'), bench_models=B.get('n_models'), engines=rows,
           tsj_noise=B.get('tsj_noise'), tsj_reps=B.get('tsj_reps'), rust_noise=B.get('rust_noise'),
           python_note='Python ran the %d fast models and a %d-model sample of the %d slower ones.'
           % (S['python']['fast_n'], S['python']['slow_run'], S['python']['slow_n']),
           controls=dict(epa_rerun='%d of %d' % (S['controls']['epa_rerun_same'], S['controls']['epa_rerun_n']),
                         fma='%d of %d' % (S['controls']['fma_all_n'] - S['controls']['fma_all_same'],
                                           S['controls']['fma_all_n'])))
LM = S.get('libm') or {}
if LM.get('generic_n'):
    out['libm_note'] = ('EPA\'s own results depend on the processor: glibc picks fused multiply-add versions of pow, exp, '
                        'sin and the rest on processors with FMA and AVX2, and run on its generic versions EPA changes %d of '
                        'the %d models. TypeScript and Java bring math functions of their own, so their ports carry '
                        'translations of glibc\'s FMA routines, checked bit for bit against the system library.'
                        % (LM['generic_n'] - LM['generic_same'], LM['generic_n']))
    NC = LM.get('native_ctl') or {}
    if NC.get('TypeScript') and NC.get('Java'):
        out['libm_note'] += (' Built with their languages\' own Math instead, TypeScript differed from EPA on %d of %d '
                             'control models and Java on %d of %d.'
                             % (NC['TypeScript']['n'] - NC['TypeScript']['same'], NC['TypeScript']['n'],
                                NC['Java']['n'] - NC['Java']['same'], NC['Java']['n']))
        JA = (LM.get('native_ctl_all') or {}).get('Java')
        if JA:
            out['libm_note'] = out['libm_note'][:-1] + ' (%d of all %d).' % (JA['n'] - JA['same'], JA['n'])
json.dump(out, open(sys.argv[1], 'w'), indent=1)
print('wrote', sys.argv[1], [r['name'] for r in rows])
